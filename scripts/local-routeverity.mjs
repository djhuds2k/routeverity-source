import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createConnection } from "node:net";
import { dirname, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = resolve(root, "apps", "web", ".env.local");
const project = "routeverity-baseline";
const marker = "# Generated by scripts/local-routeverity.mjs; local baseline only.";
const services = ["mysql", "planetscale-proxy", "redis", "redis-rest", "mailhog"];
const ports = {
  mysql: { "3306/tcp": 13306 },
  "planetscale-proxy": { "3900/tcp": 13900 },
  redis: {},
  "redis-rest": { "80/tcp": 18079 },
  mailhog: { "1025/tcp": 11025, "8025/tcp": 18025 },
};

function run(command, args, label, timeout = 30_000) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    timeout,
    windowsHide: true,
  });
  // Compose errors can contain interpolated secrets. Never print subprocess output.
  if (result.error || result.status !== 0) {
    throw new Error(`${label} failed. Check Docker availability and the documented local configuration; subprocess output is suppressed to protect credentials.`);
  }
  return result.stdout.trim();
}

function ensureIgnored() {
  let ancestor = root;
  while (!existsSync(resolve(ancestor, ".git")) && dirname(ancestor) !== ancestor)
    ancestor = dirname(ancestor);
  if (!existsSync(resolve(ancestor, ".git"))) {
    const patterns = readFileSync(resolve(root, ".gitignore"), "utf8").split(/\r?\n/);
    if (!patterns.includes(".env*.local"))
      throw new Error("Source archive is missing the required local-environment ignore rule.");
    return;
  }
  run("git", ["check-ignore", "--quiet", "apps/web/.env.local"], "Environment ignore check");
  const tracked = run("git", ["ls-files", "--", "apps/web/.env.local"], "Environment tracking check");
  if (tracked) throw new Error("Refusing to use a tracked local environment file.");
}

function loadEnv() {
  ensureIgnored();
  if (!existsSync(envPath)) throw new Error("Run setup first.");
  const text = readFileSync(envPath, "utf8");
  if (!text.startsWith(marker)) {
    throw new Error("Refusing to overwrite or use an environment file not generated by this helper. Preserve it privately before running setup.");
  }
  const env = Object.fromEntries(
    text.split(/\r?\n/).filter((line) => line && !line.startsWith("#")).map((line) => {
      const index = line.indexOf("=");
      return [line.slice(0, index), line.slice(index + 1)];
    }),
  );
  for (const key of ["NEXTAUTH_SECRET", "UPSTASH_REDIS_REST_TOKEN", "ROUTEVERITY_MYSQL_PASSWORD", "ROUTEVERITY_MYSQL_ROOT_PASSWORD"]) {
    if (!/^[a-f0-9]{64}$/.test(env[key] ?? "")) throw new Error(`Invalid local secret configuration: ${key}.`);
  }
  const expected = {
    DATABASE_URL: `mysql://routeverity:${env.ROUTEVERITY_MYSQL_PASSWORD}@127.0.0.1:13306/routeverity`,
    PLANETSCALE_DATABASE_URL: `http://routeverity:${env.ROUTEVERITY_MYSQL_PASSWORD}@127.0.0.1:13900/routeverity`,
    NEXTAUTH_URL: "http://localhost:8888",
    EMAIL_SERVER: "smtp://127.0.0.1:11025",
    EMAIL_FROM: "RouteVerity Local <noreply@routeverity.test>",
    UPSTASH_REDIS_REST_URL: "http://127.0.0.1:18079",
  };
  for (const [key, value] of Object.entries(expected)) {
    if (env[key] !== value) throw new Error(`Refusing a non-baseline endpoint or mismatched configuration: ${key}.`);
  }
  return env;
}

function setup() {
  ensureIgnored();
  if (existsSync(envPath)) {
    loadEnv();
    console.log("Existing ignored baseline environment preserved; credentials unchanged.");
    return;
  }
  const secret = () => randomBytes(32).toString("hex");
  const password = secret();
  const values = {
    DATABASE_URL: `mysql://routeverity:${password}@127.0.0.1:13306/routeverity`,
    NEXTAUTH_URL: "http://localhost:8888",
    NEXTAUTH_SECRET: secret(),
    EMAIL_SERVER: "smtp://127.0.0.1:11025",
    EMAIL_FROM: "RouteVerity Local <noreply@routeverity.test>",
    UPSTASH_REDIS_REST_URL: "http://127.0.0.1:18079",
    UPSTASH_REDIS_REST_TOKEN: secret(),
    PLANETSCALE_DATABASE_URL: `http://routeverity:${password}@127.0.0.1:13900/routeverity`,
    ROUTEVERITY_MYSQL_PASSWORD: password,
    ROUTEVERITY_MYSQL_ROOT_PASSWORD: secret(),
  };
  writeFileSync(envPath, `${marker}\n${Object.entries(values).map(([key, value]) => `${key}=${value}`).join("\n")}\n`, {
    flag: "wx",
    mode: 0o600,
  });
  console.log("Created ignored apps/web/.env.local with random credentials (not displayed).");
}

function compose(args, label, timeout) {
  loadEnv();
  return run("docker", [
    "compose", "--project-name", project,
    "--file", resolve(root, "docker-compose.routeverity.yml"),
    "--env-file", envPath, ...args,
  ], label, timeout);
}

function inspectOwnContainers() {
  const ids = compose(["ps", "--all", "--quiet", ...services], "Own container lookup").split(/\r?\n/).filter(Boolean);
  if (ids.length !== services.length) throw new Error("Baseline containers are missing; run start.");
  const containers = ids.map((id) => JSON.parse(run("docker", ["inspect", "--format", "{{json .}}", id], "Own container inspection")));
  for (const service of services) {
    const container = containers.find((item) => item.Config.Labels["com.docker.compose.service"] === service);
    if (!container || container.Config.Labels["com.docker.compose.project"] !== project) {
      throw new Error(`Container ownership mismatch: ${service}.`);
    }
    if (container.State.Status !== "running" || (container.State.Health && container.State.Health.Status !== "healthy")) {
      throw new Error(`Baseline container not healthy: ${service}.`);
    }
    const bindings = container.HostConfig.PortBindings ?? {};
    if (Object.keys(bindings).length !== Object.keys(ports[service]).length) {
      throw new Error(`Unexpected published ports: ${service}.`);
    }
    for (const [port, hostPort] of Object.entries(ports[service])) {
      if (bindings[port]?.length !== 1 || bindings[port][0].HostIp !== "127.0.0.1" || bindings[port][0].HostPort !== String(hostPort)) {
        throw new Error(`Port isolation mismatch: ${service}.`);
      }
      const activeBindings = container.NetworkSettings.Ports?.[port];
      if (activeBindings?.length !== 1 || activeBindings[0].HostIp !== "127.0.0.1" || activeBindings[0].HostPort !== String(hostPort)) {
        throw new Error(`Published loopback port is not active: ${service}.`);
      }
    }
    if (Object.keys(container.NetworkSettings.Networks).join() !== "routeverity-baseline-network") {
      throw new Error(`Unexpected container network: ${service}.`);
    }
    const expectedVolume = service === "mysql" ? "routeverity-baseline-mysql-data" : service === "redis" ? "routeverity-baseline-redis-data" : null;
    if (expectedVolume && !container.Mounts.some((mount) => mount.Type === "volume" && mount.Name === expectedVolume)) {
      throw new Error(`Storage isolation mismatch: ${service}.`);
    }
  }
  console.log("PASS: five owned containers running; loopback ports, dedicated network and volumes verified.");
}

async function jsonRequest(url, options = {}) {
  const response = await fetch(url, { ...options, signal: AbortSignal.timeout(10_000) });
  if (!response.ok) throw new Error("Local HTTP service returned an unsuccessful response.");
  return response.json();
}

async function smtpHealth() {
  await new Promise((resolvePromise, reject) => {
    const socket = createConnection({ host: "127.0.0.1", port: 11025 });
    let buffer = "";
    let phase = 0;
    const timer = setTimeout(() => fail(), 10_000);
    const fail = () => {
      clearTimeout(timer);
      socket.destroy();
      reject(new Error("Local SMTP handshake failed."));
    };
    socket.on("error", fail);
    socket.on("end", () => { if (phase !== 3) fail(); });
    socket.on("data", (data) => {
      buffer += data.toString();
      let end;
      while ((end = buffer.indexOf("\r\n")) !== -1) {
        const line = buffer.slice(0, end);
        buffer = buffer.slice(end + 2);
        if (/^\d{3}-/.test(line)) continue;
        if (phase === 0 && line.startsWith("220 ")) {
          phase = 1;
          socket.write("EHLO routeverity.test\r\n");
        } else if (phase === 1 && line.startsWith("250 ")) {
          phase = 2;
          socket.write("QUIT\r\n");
        } else if (phase === 2 && line.startsWith("221 ")) {
          phase = 3;
          clearTimeout(timer);
          socket.end();
          resolvePromise();
        } else {
          fail();
        }
      }
    });
  });
}

async function health() {
  const env = loadEnv();
  inspectOwnContainers();
  const mysqlResult = compose([
    "exec", "-T", "mysql", "sh", "-c",
    'MYSQL_PWD="$MYSQL_PASSWORD" mysql --protocol=TCP -h 127.0.0.1 -u "$MYSQL_USER" "$MYSQL_DATABASE" --batch --skip-column-names -e "SELECT DATABASE(), 1"',
  ], "Own MySQL query");
  if (mysqlResult !== "routeverity\t1") throw new Error("Local MySQL database check failed.");
  console.log("PASS: MySQL 8 authenticated SELECT against routeverity (no schema changes).");

  const sqlUrl = new URL(env.PLANETSCALE_DATABASE_URL);
  const auth = Buffer.from(`${sqlUrl.username}:${sqlUrl.password}`).toString("base64");
  const sqlResult = await jsonRequest(`${sqlUrl.origin}/psdb.v1alpha1.Database/Execute`, {
    method: "POST",
    headers: { Authorization: `Basic ${auth}`, "Content-Type": "application/json" },
    body: JSON.stringify({ query: "SELECT 1 AS routeverity_health" }),
  });
  if (sqlResult.error || sqlResult.result?.rows?.length !== 1) throw new Error("PlanetScale HTTP SQL check failed.");
  console.log("PASS: PlanetScale HTTP proxy authenticated SELECT 1.");

  const redisResult = await jsonRequest(env.UPSTASH_REDIS_REST_URL, {
    method: "POST",
    headers: { Authorization: `Bearer ${env.UPSTASH_REDIS_REST_TOKEN}`, "Content-Type": "application/json" },
    body: JSON.stringify(["PING"]),
  });
  if (redisResult.result !== "PONG") throw new Error("Redis REST PING check failed.");
  const denied = await fetch(env.UPSTASH_REDIS_REST_URL, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(["PING"]),
    signal: AbortSignal.timeout(10_000),
  });
  if (![400, 401, 403].includes(denied.status)) throw new Error("Redis REST did not reject a request without authentication.");
  console.log("PASS: Redis REST authenticated PING/PONG; unauthenticated request rejected.");

  await smtpHealth();
  const messages = await jsonRequest("http://127.0.0.1:18025/api/v2/messages");
  if (!Array.isArray(messages.items)) throw new Error("MailHog API check failed.");
  const ui = await fetch("http://127.0.0.1:18025", { signal: AbortSignal.timeout(10_000) });
  if (!ui.ok) throw new Error("MailHog UI check failed.");
  console.log("PASS: MailHog SMTP greeting/EHLO/QUIT, message API and web UI.");
  console.log("Baseline services healthy. No schema pushed; no application server started.");
}

try {
  switch (process.argv[2]) {
    case "setup":
      setup();
      break;
    case "start":
      setup();
      compose(["config", "--quiet"], "Compose configuration validation");
      compose(["up", "--detach", "--wait", "--wait-timeout", "180", ...services], "Baseline startup", 600_000);
      await health();
      break;
    case "health":
      await health();
      break;
    case "status":
      loadEnv();
      inspectOwnContainers();
      break;
    case "stop":
      compose(["stop", ...services], "Stopping own baseline containers", 120_000);
      console.log("Stopped only routeverity-baseline services; dedicated volumes preserved.");
      break;
    default:
      throw new Error("Usage: node scripts/local-routeverity.mjs <setup|start|health|status|stop>");
  }
} catch (error) {
  // Network/parser errors may include credential-bearing URLs.
  const safe = error instanceof Error && !/https?:\/\/|mysql:\/\/|[a-f0-9]{64}/i.test(error.message);
  console.error(safe ? error.message : "Local baseline check failed; details suppressed to protect credentials.");
  process.exitCode = 1;
}
