import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import nextConfig from "../../next.config";
import deployment from "../../vercel.json";

describe("portable monorepo deployment", () => {
  it("restores the lockfile and builds workspace packages before Next.js", () => {
    expect(deployment.framework).toBe("nextjs");
    expect(deployment.installCommand).toBe(
      "pnpm --filter dub-monorepo --filter web... install --frozen-lockfile --ignore-scripts",
    );
    expect(deployment.buildCommand).toBe(
      "pnpm --workspace-root routeverity:build",
    );
  });

  describe("sanitized corresponding-source export", () => {
    it("exports build inputs without private operational records or environment files", () => {
      const root = resolve(__dirname, "..", "..", "..", "..");
      const temporary = mkdtempSync(resolve(tmpdir(), "rv-source-"));
      const destination = resolve(temporary, "source");
      try {
        execFileSync(
          process.execPath,
          [
            resolve(root, "scripts", "export-routeverity-source.mjs"),
            destination,
          ],
          { cwd: root, stdio: "pipe", timeout: 20_000 },
        );
        const manifest: { files: string[] } = JSON.parse(
          readFileSync(
            resolve(destination, "routeverity-source-manifest.json"),
            "utf8",
          ),
        );
        expect(manifest.files).toEqual(
          expect.arrayContaining([
            "LICENSE.md",
            "NOTICE.md",
            "apps/web/.env.example",
            "apps/web/app/click/route.ts",
            "apps/web/instrumentation.ts",
            "apps/web/lib/axiom/axiom.ts",
            "apps/web/lib/axiom/server.ts",
            "docs/local-development.md",
            "apps/web/lib/routeverity/merchant-attribution.ts",
            "apps/web/tests/routeverity/merchant-attribution.test.ts",
            "docs/merchant-attribution-design.md",
            "docs/merchant-integration.md",
            "examples/merchant-reference/client.mjs",
            "examples/merchant-reference/client.test.mjs",
            "apps/web/tests/routeverity/merchant-reference.test.ts",
            "scripts/routeverity-build-inventory.cjs",
            "scripts/audit-routeverity-licenses.mjs",
            "scripts/prepare-routeverity-next-patch.mjs",
            "scripts/check-routeverity-vendor-patch.mjs",
            "scripts/routeverity-vendor-security.test.cjs",
            "patches/next@15.5.28.patch",
            "docs/security-vendor-patch.json",
            "scripts/routeverity-notice-fetch.test.mjs",
            "docs/licensing-audit.md",
            "docs/source-release.md",
            "docs/source-restoration.md",
            "docs/licensing-inventory.json",
            "apps/web/public/third-party-notices.txt",
          ]),
        );
        const exportedPackage: { scripts: Record<string, string> } = JSON.parse(
          readFileSync(resolve(destination, "package.json"), "utf8"),
        );
        expect(exportedPackage.scripts["routeverity:test"]).toContain(
          "examples/merchant-reference/client.test.mjs",
        );
        expect(exportedPackage.scripts["routeverity:test"]).toContain(
          "scripts/routeverity-notice-fetch.test.mjs",
        );
        execFileSync(
          process.execPath,
          [
            "--test",
            resolve(
              destination,
              "examples",
              "merchant-reference",
              "client.test.mjs",
            ),
            resolve(
              destination,
              "scripts",
              "routeverity-notice-fetch.test.mjs",
            ),
          ],
          { cwd: destination, stdio: "pipe", timeout: 15_000 },
        );
        for (const path of [
          "docs/progress.md",
          "docs/recovery-report.md",
          "docs/previous-routeverity-design-audit.md",
          "docs/completion-plan.md",
          "docs/release-readiness.md",
          "docs/decisions-required.md",
          "docs/verification-evidence.md",
          "apps/web/.env.local",
        ]) {
          expect(manifest.files).not.toContain(path);
          expect(existsSync(resolve(destination, path))).toBe(false);
        }
        const helper = resolve(destination, "scripts", "local-routeverity.mjs");
        execFileSync(process.execPath, [helper, "setup"], {
          cwd: destination,
          stdio: "pipe",
          timeout: 5_000,
        });
        const environment = readFileSync(
          resolve(destination, "apps", "web", ".env.local"),
          "utf8",
        );
        expect(
          environment.startsWith(
            "# Generated by scripts/local-routeverity.mjs; local baseline only.",
          ),
        ).toBe(true);
        execFileSync(process.execPath, [helper, "setup"], {
          cwd: destination,
          stdio: "pipe",
          timeout: 5_000,
        });
        expect(
          readFileSync(
            resolve(destination, "apps", "web", ".env.local"),
            "utf8",
          ) === environment,
        ).toBe(true);
      } finally {
        rmSync(temporary, { recursive: true, force: true });
      }
    }, 30_000);
  });

  it("traces runtime dependencies from the workspace root", () => {
    expect(nextConfig.outputFileTracingRoot).toBe(
      resolve(__dirname, "..", "..", "..", ".."),
    );
  });
});
