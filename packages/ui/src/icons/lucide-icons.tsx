import * as Lucide from "lucide-react";
import { forwardRef } from "react";

export type ReplacementIconProps = Lucide.LucideProps & {
  variant?: "outline" | "fill";
};

function compatibleIcon(Component: Lucide.LucideIcon) {
  const Icon = forwardRef<SVGSVGElement, ReplacementIconProps>(
    ({ variant, fill, ...props }, ref) => (
      <Component
        ref={ref}
        fill={fill ?? (variant === "fill" ? "currentColor" : "none")}
        {...props}
      />
    ),
  );
  Icon.displayName = Component.displayName;
  return Icon;
}

